import Foundation

struct SherwinWilliamsColor: ColorDataProtocol {
    let id: String
    let name: String
    let hex: String
    let rgb: RGB
    let cmyk: CMYK
    
    init(name: String, number: String, hex: String) {
        self.id = "SW \(number)"
        self.name = name
        self.hex = hex
        self.rgb = SherwinWilliamsColor.hexToRGB(hex)
        self.cmyk = SherwinWilliamsColor.hexToCMYK(hex)
    }
    
    private static func hexToRGB(_ hex: String) -> RGB {
        var hexString = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        if hexString.hasPrefix("#") {
            hexString = String(hexString.dropFirst())
        }
        
        var rgb: UInt64 = 0
        Scanner(string: hexString).scanHexInt64(&rgb)
        
        let r = Int((rgb & 0xFF0000) >> 16)
        let g = Int((rgb & 0x00FF00) >> 8)
        let b = Int(rgb & 0x0000FF)
        
        return RGB(r: r, g: g, b: b)
    }
    
    private static func hexToCMYK(_ hex: String) -> CMYK {
        let rgb = hexToRGB(hex)
        
        let r = Double(rgb.r) / 255.0
        let g = Double(rgb.g) / 255.0
        let b = Double(rgb.b) / 255.0
        
        let k = 1.0 - max(r, g, b)
        var c, m, y: Double
        
        if k == 1.0 {
            c = 0.0
            m = 0.0
            y = 0.0
        } else {
            c = (1.0 - r - k) / (1.0 - k)
            m = (1.0 - g - k) / (1.0 - k)
            y = (1.0 - b - k) / (1.0 - k)
        }
        
        return CMYK(
            c: Int(c * 100),
            m: Int(m * 100),
            y: Int(y * 100),
            k: Int(k * 100)
        )
    }
}

